/** Средняя оценка аттестата → вероятность поступления на бюджет. */
export function collegeChance(avg: number, score: number) {
  if (avg >= score) return 'ok' as const
  if (avg >= score - 0.15) return 'edge' as const
  return 'low' as const
}

